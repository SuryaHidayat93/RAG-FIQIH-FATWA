    for q in DI_LUAR_CAKUPAN_QUESTIONS:
        dataset.append({"text": q, "label": "di_luar_cakupan"})

    output_path = Path("data/router_dataset.json")
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(dataset, f, ensure_ascii=False, indent=2)

    counts = {
        "fatwa": len(FATWA_QUESTIONS),
        "fiqih": len(FIQIH_QUESTIONS),
        "keduanya": len(KEDUANYA_QUESTIONS),
        "di_luar_cakupan": len(DI_LUAR_CAKUPAN_QUESTIONS),
        "total": len(dataset),
    }
    print(f"Dataset berhasil disimpan ke: {output_path}")
    print(f"Distribusi label: {counts}")
    return counts


